"""Список устройств, переживающий недоступность облака.

Состав устройств интеграция знает только из облака: имена, облачные id и
MAC приходят из `GET /devices`. Пока облако отвечает, это незаметно — но
19.10.2026 вендор отклонил вход (403 «Аккаунт не допущен к тестированию»),
а затем перенёс API на другой адрес, и 443 перестал отвечать вовсе.
Интеграция падала на входе, сущности исчезали, и локальный канал — который
для таких случаев и задумывался — не поднимался вовсе, потому что падение
происходило раньше.

Поэтому состав устройств сохраняется в запись конфигурации и при недоступном
облаке восстанавливается оттуда: сущности на месте, а значения и доступность
приходят с локального канала.

Храним только то, что нужно для создания сущностей: облачный id, MAC, имя,
модель и версию прошивки. Владельца, сессии и телеметрию не кэшируем —
телеметрия устареет за минуты, а владелец здесь вообще ни к чему.

Модуль не зависит от Home Assistant и проверяется тестами на голом Python.
"""

from __future__ import annotations

from typing import Any

# Поля, которые переживают перезапуск. Этого набора хватает платформам,
# чтобы создать те же сущности с теми же идентификаторами.
CACHED_FIELDS = ("id", "mac", "name", "model", "fw_ver", "type")


def cache_payload(devices: Any) -> list[dict[str, Any]]:
    """Что из ответа облака стоит сохранить."""
    result: list[dict[str, Any]] = []
    for dev in devices or []:
        if not isinstance(dev, dict) or dev.get("id") is None:
            continue
        result.append({key: dev[key] for key in CACHED_FIELDS if key in dev})
    return result


def cache_fingerprint(devices: Any) -> tuple:
    """Отпечаток состава устройств.

    Запись конфигурации сохраняется на диск, поэтому переписывать её на
    каждый опрос (раз в 30 секунд) нельзя. Отпечаток меняется, только если
    поменялся сам состав: появилось устройство, сменилось имя или MAC.
    """
    return tuple(
        tuple(sorted(dev.items(), key=lambda kv: kv[0]))
        for dev in sorted(cache_payload(devices), key=lambda d: str(d.get("id")))
    )


def restore(cached: Any) -> dict[str, Any]:
    """Данные координатора из кэша: устройства есть, показаний пока нет.

    `online: False` намеренно: пока с устройством никто не говорил, честнее
    показать сущность недоступной, чем выдать выдуманное состояние. Как
    только придёт первый кадр локального канала, слияние поднимет флаг.
    """
    devices: list[dict[str, Any]] = []
    for dev in cache_payload(cached):
        devices.append({**dev, "online": False, "condition": {}, "settings": {}})
    return {"devices": devices, "states": {}}
